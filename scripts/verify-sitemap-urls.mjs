/**
 * Probe every <loc> in the deployed sitemap against production (or BASE_URL).
 * Set VERIFY_LOCAL_SITEMAP=1 to inspect public/sitemap.xml instead.
 * Writes docs/sitemap-http-verification.md and exits nonzero on redirects/failures.
 * Usage: node scripts/verify-sitemap-urls.mjs
 */

import fs from 'fs/promises';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, '..');

const BASE_URL =
  process.env.BASE_URL?.replace(/\/$/, '') ?? 'https://justlegalsolutions.org';
const LOCAL_SITEMAP = path.join(ROOT, 'public', 'sitemap.xml');
const SITEMAP_URL = process.env.SITEMAP_URL ?? `${BASE_URL}/sitemap.xml`;
const USE_LOCAL_SITEMAP = process.env.VERIFY_LOCAL_SITEMAP === '1';
const OUT_MD = path.join(ROOT, 'docs', 'sitemap-http-verification.md');

const CONCURRENCY = Number.parseInt(process.env.VERIFY_CONCURRENCY ?? '10', 10);
const TIMEOUT_MS = Number.parseInt(process.env.VERIFY_TIMEOUT_MS ?? '20000', 10);

async function probeOnce(url, method) {
  const controller = new AbortController();
  const tid = setTimeout(() => controller.abort(), TIMEOUT_MS);
  try {
    const res = await fetch(url, {
      method,
      redirect: 'manual',
      signal: controller.signal,
      headers: { 'User-Agent': 'JLS-sitemap-verify/1.0' },
    });
    clearTimeout(tid);
    const location = res.headers.get('location');
    const finalUrl = location ? new URL(location, url).toString() : res.url;
    return { ok: res.ok, status: res.status, finalUrl };
  } catch (e) {
    clearTimeout(tid);
    const msg = e.name === 'AbortError' ? 'TIMEOUT' : String(e.message);
    return { ok: false, status: msg, finalUrl: url };
  }
}

async function probe(url) {
  let r = await probeOnce(url, 'HEAD');
  if (typeof r.status === 'number' && (r.status === 405 || r.status === 501)) {
    r = await probeOnce(url, 'GET');
  }
  if (typeof r.status === 'number' && r.status === 405) {
    r = await probeOnce(url, 'GET');
  }
  return r;
}

async function main() {
  let xml;
  let sitemapSource;

  if (USE_LOCAL_SITEMAP) {
    xml = await fs.readFile(LOCAL_SITEMAP, 'utf8');
    sitemapSource = LOCAL_SITEMAP;
  } else {
    const sitemapRes = await fetch(SITEMAP_URL, {
      cache: 'no-store',
      headers: {
        Accept: 'application/xml,text/xml,*/*',
        'User-Agent': 'JLS-sitemap-verify/1.0',
      },
    });
    if (!sitemapRes.ok) {
      throw new Error(`Unable to fetch ${SITEMAP_URL}: HTTP ${sitemapRes.status}`);
    }
    xml = await sitemapRes.text();
    sitemapSource = SITEMAP_URL;
  }

  const urls = [...xml.matchAll(/<loc>([^<]+)<\/loc>/g)].map((m) => {
    try {
      return new URL(m[1]).toString().replace(/\/$/, '');
    } catch {
      return m[1].trim().replace(/\/$/, '');
    }
  });

  const unique = [...new Set(urls)];
  /** @type {Array<{ url: string; status: number|string; ok: boolean; finalUrl: string }>} */
  const results = [];

  let i = 0;
  async function worker() {
    while (i < unique.length) {
      const idx = i++;
      const url = unique[idx];
      const r = await probe(url);
      results[idx] = { url, ok: r.ok, status: r.status, finalUrl: r.finalUrl };
    }
  }

  await Promise.all(
    Array.from({ length: Math.min(CONCURRENCY, unique.length) }, () => worker())
  );

  const bad = results.filter(
    (r) => !(typeof r.status === 'number' && r.status >= 200 && r.status < 300)
  );
  const timeouts = bad.filter((r) => r.status === 'TIMEOUT');
  const redirects = bad.filter(
    (r) => typeof r.status === 'number' && r.status >= 300 && r.status < 400
  );
  const failures = bad.filter(
    (r) => !(typeof r.status === 'number' && r.status >= 300 && r.status < 400)
  );

  const now = new Date().toISOString();
  let md = `<!-- Generated by scripts/verify-sitemap-urls.mjs — DO NOT edit by hand; re-run npm run verify:sitemap -->\n\n`;
  md += `# Sitemap HTTP verification\n\n`;
  md += `- **When:** ${now}\n`;
  md += `- **Sitemap source:** ${sitemapSource}\n`;
  md += `- **Base:** ${BASE_URL}\n`;
  md += `- **URLs in <loc> (deduped):** ${unique.length}\n`;
  md += `- **Redirects (invalid in sitemap):** ${redirects.length}\n`;
  md += `- **Failures (non-2xx, excluding redirects):** ${failures.length}\n`;
  md += `- **Timeouts:** ${timeouts.length}\n\n`;

  md += `## Rows outside 2xx success range\n\n`;
  md += bad.length === 0
    ? `_None — every sitemap URL returned HTTP 2xx without redirecting._\n\n`
    : `| URL | Status | Redirect target / final URL |\n|-----|--------|-----------------------------|\n`;
  for (const r of bad.sort((a, b) => String(a.status).localeCompare(String(b.status)))) {
    md += `| ${r.url.replace(/\|/g, '\\|')} | ${r.status} | ${String(r.finalUrl).replace(/\|/g, '\\|')} |\n`;
  }

  md += `\n## All results (compact)\n\n`;
  md += `<details>\n<summary>${unique.length} rows</summary>\n\n`;
  md += `| Status | URL |\n|--------|-----|\n`;
  for (const r of [...results].sort((a, b) => a.url.localeCompare(b.url))) {
    md += `| ${r.status} | ${r.url.replace(/\|/g, '\\|')} |\n`;
  }
  md += `\n</details>\n`;

  await fs.mkdir(path.dirname(OUT_MD), { recursive: true });
  await fs.writeFile(OUT_MD, md, 'utf8');
  console.log(`Wrote ${OUT_MD}`);
  console.log(`Sitemap source: ${sitemapSource}`);
  console.log(`URLs: ${unique.length} | Redirects: ${redirects.length} | Failures: ${failures.length}`);
  if (bad.length > 0) process.exitCode = 1;
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
